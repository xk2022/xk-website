#!/usr/bin/env python3
"""Regenerate a reviewed core asset from a pinned master and repo codepoints.
Requires external FontTools4.61.1/Brotli1.1.0; never changes App dependencies.
This regenerates the reviewed glyph set, not a fresh HTML/source corpus audit.
"""
import argparse, hashlib, json
from pathlib import Path
from fontTools import subset
from fontTools.ttLib import TTFont

p=argparse.ArgumentParser(description=__doc__)
p.add_argument('--master',type=Path,required=True)
p.add_argument('--master-sha256',required=True)
p.add_argument('--codepoints',type=Path,required=True)
p.add_argument('--modified',type=int,required=True)
p.add_argument('--expected-sha256',required=True)
p.add_argument('--output',type=Path,required=True)
a=p.parse_args()
sha=lambda data:hashlib.sha256(data).hexdigest()
if a.output.exists():p.error('Refusing to overwrite an existing asset')
if sha(a.master.read_bytes())!=a.master_sha256:p.error('Pinned master SHA mismatch')
record=json.loads(a.codepoints.read_text())
core=set(record['core'] if isinstance(record,dict) else record)
f=TTFont(a.master,recalcTimestamp=False)
if not core<=set(f.getBestCmap()):p.error('Master does not cover reviewed codepoints')
selectors={selector for t in f['cmap'].tables if t.format==14 for selector,items in t.uvsDict.items() if any(base in core for base,glyph in items)}
options=subset.Options()
for key,value in dict(layout_features=['*'],layout_scripts=['*'],layout_closure=True,glyph_names=True,name_IDs=['*'],name_legacy=True,name_languages=['*'],notdef_glyph=True,notdef_outline=True,recommended_glyphs=True,recalc_timestamp=False).items():setattr(options,key,value)
s=subset.Subsetter(options=options)
s.populate(unicodes=core|selectors)
s.subset(f)
if set(f.getBestCmap())!=core:raise ValueError('Bidi/Unicode closure changed reviewed core; update the audited codepoint list first')
f.recalcTimestamp=False
f['head'].modified=a.modified
f.flavor='woff2'
f.save(a.output)
actual=sha(a.output.read_bytes())
print(json.dumps({'output':str(a.output),'coreCodepoints':len(core),'uvsSelectors':sorted(selectors),'bytes':a.output.stat().st_size,'sha256':actual,'expectedSha256':a.expected_sha256}))
if actual!=a.expected_sha256:raise ValueError('Generated bytes differ; output retained for diagnosis, no existing asset replaced')
